"""Generate the container build file for a deployment.

Users never write a Dockerfile: ``wicklight deploy`` renders one from the deploy
file. The result is a two-stage build — dependencies installed with ``uv`` in a
full Python image, then copied into a hardened Google *distroless* runtime that
has no shell and no package manager, runs as a non-root user, and is designed to
run with a read-only root filesystem (only the trace mount is writable).
"""

from __future__ import annotations

# The distroless runtime: no shell, no package manager, non-root (uid 65532),
# Python 3.11. Pinned by tag here; a deployment can pin by digest later.
RUNTIME_IMAGE = "gcr.io/distroless/python3-debian12:nonroot"
BUILDER_IMAGE = "python:3.11-slim"
# distroless python lives here; it is also the image's default entrypoint.
RUNTIME_PYTHON = "/usr/bin/python3.11"
DEPS_DIR = "/app/deps"
APP_DIR = "/app"


def render_containerfile(
    *,
    wheel_filename: str,
    agent_filename: str,
    deploy_filename: str,
) -> str:
    """Render the Containerfile that builds a deployment image.

    ``wheel_filename`` is the built ``wicklight`` wheel in the build context;
    ``agent_filename`` and ``deploy_filename`` are copied in read-only. The agent
    file and deploy file are baked in; secret *values* never are — they are
    injected as runtime environment at ``docker run`` time (DTN-255).
    """
    return f"""\
# Generated by `wicklight deploy` — do not edit by hand.
# Two stages: install dependencies with uv, then copy them into a hardened,
# shell-less, non-root distroless runtime.

FROM {BUILDER_IMAGE} AS builder
RUN pip install --no-cache-dir uv
WORKDIR /build
COPY {wheel_filename} ./
# Install Wicklight (and its provider/tool plugins) into a flat directory that
# the distroless Python can import directly — no venv symlinks to a missing base.
RUN uv pip install --no-cache --target {DEPS_DIR} ./{wheel_filename}

FROM {RUNTIME_IMAGE}
COPY --from=builder {DEPS_DIR} {DEPS_DIR}
COPY {agent_filename} {APP_DIR}/agent.md
COPY {deploy_filename} {APP_DIR}/deploy.yaml
ENV PYTHONPATH={DEPS_DIR}
ENV WICKLIGHT_DEPLOY={APP_DIR}/deploy.yaml
ENV WICKLIGHT_AGENT={APP_DIR}/agent.md
WORKDIR {APP_DIR}
# distroless :nonroot already runs as uid 65532; make it explicit.
USER nonroot
ENTRYPOINT ["{RUNTIME_PYTHON}", "-m", "wicklight.deploy.entry"]
"""
